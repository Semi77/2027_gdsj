/**
  * @brief USART3 接收中断只缓存字节并重新开启接收。
  * @param UartHandle 完成本次接收的串口句柄。
  * @retval 无。
  */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *UartHandle)
{
    if (UartHandle->Instance == USART3)
    {
        ChassisLink_RxByte(Usart3_Receive_buf[0]);
        (void)HAL_UART_Receive_IT(&huart3, Usart3_Receive_buf, sizeof(Usart3_Receive_buf));
    }
}

/**
  * @brief USART3 接收错误时立即禁能并恢复接收，主循环丢弃残帧。
  * @param UartHandle 发生错误的串口句柄。
  * @retval 无。
  */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *UartHandle)
{
    if (UartHandle->Instance == USART3)
    {
        ChassisLink_RxError();
        (void)HAL_UART_AbortReceive(UartHandle);
        __HAL_UART_CLEAR_OREFLAG(UartHandle);
        (void)HAL_UART_Receive_IT(&huart3, Usart3_Receive_buf, sizeof(Usart3_Receive_buf));
    }
}
